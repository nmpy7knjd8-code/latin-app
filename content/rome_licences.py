"""Consolidated licence register for every image used by rome-cards.json.
Re-queries the Wikimedia Commons API for each file and writes img/rome/LICENCES.md + licences.json."""
import json,os,sys,urllib.request,urllib.parse,re
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
H={'User-Agent':'LatinAppResearch/1.0 (garrett)'}
C=json.load(open(os.path.join(HERE,'rome-cards.json')))
rows={}
for c in C:
    im=c['image']; rows.setdefault(im['src'],dict(src=im['src'],source_url=im['source_url'],declared=im['license'],credit=im['credit'],cards=[]))['cards'].append(c['id'])
for r in rows.values():
    if 'commons.wikimedia.org/wiki/File:' not in r['source_url']:
        r.update(commons_licence='(not on Commons: '+r['declared']+' per source)',artist='',attribution_required='',licence_url='',match=True); continue
    f=urllib.parse.unquote(r['source_url'].split('File:')[-1]).replace('_',' ')
    q=urllib.parse.urlencode({'action':'query','format':'json','titles':'File:'+f,'prop':'imageinfo','iiprop':'extmetadata'})
    pp=list(json.load(urllib.request.urlopen(urllib.request.Request('https://commons.wikimedia.org/w/api.php?'+q,headers=H),timeout=30))['query']['pages'].values())[0]
    if 'imageinfo' not in pp:
        r.update(commons_licence='FILE NOT FOUND',artist='',attribution_required='',licence_url='',match=False); continue
    p=pp
    m=p['imageinfo'][0]['extmetadata']
    g=lambda k: re.sub(r'<[^>]+>','',m.get(k,{}).get('value','')).strip()
    r.update(commons_licence=g('LicenseShortName'),artist=g('Artist')[:120],attribution_required=g('AttributionRequired'),licence_url=g('LicenseUrl'))
    def norm(x): return x.lower().replace('public domain','pd').replace('pdm','pd').replace('pd-art','pd').strip()
    r['match']=norm(r['commons_licence'])==norm(r['declared']) or (norm(r['declared'])=='pd' and 'public domain' in r['commons_licence'].lower())
R=sorted(rows.values(),key=lambda r:r['src'])
json.dump(R,open(os.path.join(HERE,'img','rome','licences.json'),'w'),ensure_ascii=False,indent=1)
with open(os.path.join(HERE,'img','rome','LICENCES.md'),'w') as f:
    f.write('# Image licences: Rome cards\n\nGenerated by rome_licences.py from the live Commons API. CC BY / CC BY-SA images need the credit line shown (the card back shows `credit` + licence).\n\n| file | licence (Commons) | declared | attribution | artist | source | cards |\n|---|---|---|---|---|---|---|\n')
    for r in R: f.write(f"| {r['src']} | {r['commons_licence']} | {r['declared']}{'' if r['match'] else ' ⚠'} | {r['attribution_required'] or '-'} | {r['artist'].replace('|','/')} | {r['source_url']} | {', '.join(r['cards'])} |\n")
print(len(R),'images;',sum(not r['match'] for r in R),'mismatches')
for r in R:
    if not r['match']: print('MISMATCH',r['src'],r['commons_licence'],r['declared'])
